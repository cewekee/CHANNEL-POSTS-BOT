def btc_line(change: float | None) -> str:
    if change is None:
        return "Рынок просыпается, смотрим, куда пойдёт день."
    chg = f"{change:+.1f}%"
    a = abs(change)
    key = "flat" if a < 1 else ("up" if 0 < change < 3.5 else "pump" if change >= 3.5 else
                                "down" if change > -3.5 else "dump")
    return random.choice(BTC_LINES[key]).format(chg=chg)


